// Generates TypeScript types for kupra's resources from the CRDs in charts/kupra/crds.
import { format, resolveConfig } from 'prettier';
import { parse } from 'yaml';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

type Schema = {
  type?: string;
  description?: string;
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  additionalProperties?: Schema | boolean;
  enum?: unknown[];
  nullable?: boolean;
  'x-kubernetes-int-or-string'?: boolean;
  'x-kubernetes-preserve-unknown-fields'?: boolean;
};

type CRD = {
  spec: {
    group: string;
    names: { kind: string; plural: string };
    scope: 'Namespaced' | 'Cluster';
    versions: { name: string; storage: boolean; schema: { openAPIV3Schema: Schema } }[];
  };
};

const crdDir = path.resolve(import.meta.dirname, '../../charts/kupra/crds');
const output = path.resolve(import.meta.dirname, '../src/lib/kube/kupra.gen.ts');

const comment = (description: string | undefined, indent: string) =>
  description
    ? `${indent}/** ${description
        .replaceAll('*/', String.raw`*\/`)
        .split('\n')
        .join(`\n${indent} * `)} */\n`
    : '';

const propertyName = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

const typeOf = (schema: Schema, indent: string): string => {
  const type = baseType(schema, indent);
  return schema.nullable ? `${type} | null` : type;
};

const baseType = (schema: Schema, indent: string): string => {
  if (schema['x-kubernetes-int-or-string']) {
    return 'number | string';
  }
  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  }
  switch (schema.type) {
    case 'string': {
      return 'string';
    }
    case 'integer':
    case 'number': {
      return 'number';
    }
    case 'boolean': {
      return 'boolean';
    }
    case 'array': {
      if (!schema.items) {
        throw new Error('array without items');
      }
      const items = typeOf(schema.items, indent);
      return /[ |]/.test(items) && !items.startsWith('{') ? `(${items})[]` : `${items}[]`;
    }
    case 'object': {
      if (schema.properties) {
        return objectType(schema, indent);
      }
      if (typeof schema.additionalProperties === 'object') {
        return `Record<string, ${typeOf(schema.additionalProperties, indent)}>`;
      }
      return 'Record<string, unknown>';
    }
    case undefined: {
      if (schema['x-kubernetes-preserve-unknown-fields']) {
        return 'unknown';
      }
    }
  }
  throw new Error(`unsupported schema type ${String(schema.type)}`);
};

const objectType = (schema: Schema, indent: string, overrides: Record<string, string> = {}): string => {
  const required = new Set(schema.required);
  const inner = `${indent}  `;
  const fields = Object.entries(schema.properties ?? {}).map(([name, property]) => {
    const optional = required.has(name) ? '' : '?';
    const type = overrides[name] ?? typeOf(property, inner);
    return `${comment(property.description, inner)}${inner}${propertyName(name)}${optional}: ${type};\n`;
  });
  return `{\n${fields.join('')}${indent}}`;
};

const crds = readdirSync(crdDir)
  .filter((file) => file.endsWith('.yaml'))
  .toSorted((a, b) => a.localeCompare(b))
  .map((file) => parse(readFileSync(path.join(crdDir, file), 'utf8')) as CRD);

const declarations: string[] = [];
const resources: string[] = [];
for (const { spec } of crds) {
  const version = spec.versions.find((candidate) => candidate.storage);
  if (!version) {
    throw new Error(`${spec.names.plural}.${spec.group} has no storage version`);
  }
  const { kind, plural } = spec.names;
  const apiVersion = `${spec.group}/${version.name}`;
  const schema = version.schema.openAPIV3Schema;
  const body = objectType(schema, '', {
    apiVersion: JSON.stringify(apiVersion),
    kind: JSON.stringify(kind),
    metadata: 'ObjectMeta',
  });
  declarations.push(`${comment(schema.description, '')}export type ${kind} = ${body};\n`);
  resources.push(
    `  ${kind}: { group: ${JSON.stringify(spec.group)}, version: ${JSON.stringify(version.name)}, plural: ${JSON.stringify(plural)}, namespaced: ${spec.scope === 'Namespaced'} },\n`,
  );
}

const source = `// Code generated by scripts/generate-types.ts from charts/kupra/crds. DO NOT EDIT.

import type { ObjectMeta } from './meta.ts';

${declarations.join('\n')}
/** Resources are the API group, version and plural of each of kupra's kinds. */
export const resources = {
${resources.join('')}} as const;

/** Kinds maps each of kupra's kinds to its type. */
export type Kinds = {
${crds.map(({ spec }) => `  ${spec.names.kind}: ${spec.names.kind};\n`).join('')}};
`;

const config = await resolveConfig(output);
writeFileSync(output, await format(source, { ...config, filepath: output }));
